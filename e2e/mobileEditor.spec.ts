import { expect, test } from '@playwright/test'

test('mobile settings persist theme choice and open existing sync details', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const settings = page.getByRole('region', { name: '设置', exact: true })
  await expect(settings).toBeVisible()
  await page.getByRole('radio', { name: '暗夜模式' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('radio', { name: '暗夜模式' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '返回便签' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('radio', { name: '暗夜模式' })).toBeChecked()
  await page.getByRole('radio', { name: '白天模式' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await settings.getByRole('button', { name: /云同步/ }).click()
  await expect(page.getByRole('dialog', { name: '数据与同步', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(settings).toBeVisible()
  await page.getByRole('button', { name: '返回便签' }).click()
  await expect(page.getByRole('button', { name: '设置', exact: true })).toBeVisible()
})

for (const width of [360, 430]) {
  test(`mobile editor at ${width}px keeps formatting usable with pending uploads`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.goto('/')
    await page.getByRole('button', { name: '新建便签', exact: true }).click()
    const body = page.locator('.ProseMirror')
    await expect(page.locator('.mobile-note-meta')).toBeVisible()
    await body.click()
    await expect(page.locator('.mobile-note-meta')).toBeHidden()
    await page.getByRole('button', { name: '字体', exact: true }).click()
    await expect(page.getByRole('group', { name: '字体设置' })).toBeVisible()
    await page.getByRole('button', { name: '加粗', exact: true }).click()
    await page.keyboard.insertText('手机加粗内容')
    await expect(body.locator('strong')).toHaveText('手机加粗内容')
    await page.getByRole('button', { name: '收起键盘和字体面板' }).click()
    await expect(page.locator('.mobile-note-meta')).toContainText('本地已保存')
    await expect(page.getByRole('group', { name: '字体设置' })).toBeHidden()
    const bounds = await page.getByRole('toolbar', { name: '常用排版' }).boundingBox()
    expect(bounds?.width).toBeGreaterThan(300)
    expect((bounds?.y ?? 0) + (bounds?.height ?? 0)).toBeLessThanOrEqual(800)
    await page.reload()
    await page.getByRole('heading', { name: '无标题', exact: true }).click()
    await expect(body.locator('strong')).toHaveText('手机加粗内容')
    await page.getByRole('button', { name: '待办清单' }).click()
    await expect(body.locator('ul[data-type="taskList"]')).toBeVisible()
    await page.getByRole('button', { name: '收起键盘和字体面板' }).click()
    await expect(page.locator('.mobile-sync-status')).toContainText('本地已保存')
    await page.getByRole('button', { name: '返回列表' }).click()
    const search = page.getByRole('textbox', { name: '搜索便签', exact: true })
    await expect(page.locator('.mobile-note-list-container .note-list-header')).toHaveCount(0)
    await expect(search).toHaveAttribute('placeholder', '搜索便签')
    await search.fill('手机加粗')
    await expect(page.getByRole('heading', { name: '无标题', exact: true })).toBeVisible()
    await search.fill('没有这条便签')
    await expect(page.getByText('没有找到便签', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '清除搜索' }).click()
    await expect(search).toHaveValue('')
    const createBounds = await page.getByRole('button', { name: '新建便签', exact: true }).boundingBox()
    expect(createBounds?.x).toBeGreaterThan(width / 2)
    expect(createBounds?.y).toBeGreaterThan(650)
    expect((createBounds?.y ?? 0) + (createBounds?.height ?? 0)).toBeLessThanOrEqual(800)
  })
}

test('mobile more menu reuses pin, folder move and recoverable deletion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '新建便签', exact: true }).click()
  await page.getByRole('textbox', { name: '便签标题' }).fill('手机菜单')
  await page.getByRole('button', { name: '收起键盘和字体面板' }).click()
  await expect(page.locator('.mobile-sync-status')).toContainText('本地已保存')
  await page.getByRole('button', { name: '更多便签操作' }).click()
  await page.getByRole('button', { name: '置顶便签', exact: true }).click()
  await page.getByRole('button', { name: '更多便签操作' }).click()
  await expect(page.getByRole('button', { name: '取消置顶' })).toBeVisible()
  await expect(page.getByRole('button', { name: '管理文件夹', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '新建便签', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '关闭操作菜单' }).click()
  await page.getByRole('button', { name: '返回列表' }).click()
  await page.getByRole('button', { name: '打开菜单' }).click()
  await expect(page.getByRole('button', { name: '文件夹', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '文件夹', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建文件夹' }).click()
  await page.getByRole('textbox', { name: '新文件夹名称' }).fill('移动目标')
  await page.getByRole('textbox', { name: '新文件夹名称' }).press('Enter')
  await expect(page.getByText('移动目标', { exact: true })).toBeVisible()
  await page.locator('.sidebar-overlay').click({ position: { x: 350, y: 10 } })
  await page.getByRole('heading', { name: '手机菜单', exact: true }).click()
  await page.getByRole('button', { name: '更多便签操作' }).click()
  await page.getByRole('button', { name: '移动便签', exact: true }).click()
  await page.getByRole('button', { name: '移动目标', exact: true }).click()
  await page.getByRole('button', { name: '更多便签操作' }).click()
  await page.getByRole('button', { name: '移动便签', exact: true }).click()
  await expect(page.getByRole('button', { name: '移动目标', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '更多便签操作' }).click()
  await page.getByRole('button', { name: '移入回收站', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '便签标题' })).toBeHidden()
  await expect(page.getByRole('heading', { name: '手机菜单', exact: true })).toBeHidden()
})
